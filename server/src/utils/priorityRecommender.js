/**
 * Recommends an issue priority level based on transparent, explainable heuristic scoring.
 * Authorities retain final decision-making rights.
 */
function recommendPriority({ categoryName, title, description, supportCount = 0, isSensitiveLocation = false, hoursSinceReported = 0 }) {
  let score = 20; // Baseline: MEDIUM starts at ~35-50
  const factors = [];

  const text = `${title || ''} ${description || ''}`.toLowerCase();

  // Category Baseline Weight
  const cat = (categoryName || '').toLowerCase();
  if (cat.includes('drainage') || cat.includes('water leakage')) {
    score += 15;
    factors.push('Public health & sanitation risk from water/drainage');
  } else if (cat.includes('road') || cat.includes('pothole')) {
    score += 15;
    factors.push('Traffic safety and vehicular hazard');
  } else if (cat.includes('streetlight')) {
    score += 10;
    factors.push('Public safety and night transit');
  } else if (cat.includes('garbage')) {
    score += 10;
    factors.push('Public hygiene and vector-borne illness risk');
  }

  // Critical hazard keywords
  const criticalWords = [
    'spark', 'live wire', 'electrocution', 'accident', 'fire', 'collapsed',
    'hospital', 'school', 'emergency', 'casualty', 'flooded homes', 'danger', 'hazard', 'severe'
  ];
  const matchedCritical = criticalWords.filter(w => text.includes(w));
  if (matchedCritical.length > 0) {
    score += Math.min(35, matchedCritical.length * 15);
    factors.push(`Urgent safety keywords detected: "${matchedCritical.join(', ')}"`);
  }

  // High hazard keywords
  const highWords = ['blocking road', 'huge pit', 'overflowing', 'toxic', 'broken pipeline', 'deep pothole', 'elderly', 'children'];
  const matchedHigh = highWords.filter(w => text.includes(w));
  if (matchedHigh.length > 0) {
    score += Math.min(20, matchedHigh.length * 8);
    factors.push(`Hazard indicators detected: "${matchedHigh.join(', ')}"`);
  }

  // Location sensitivity
  if (isSensitiveLocation || text.includes('school') || text.includes('hospital') || text.includes('main road') || text.includes('market')) {
    score += 15;
    factors.push('High-density public zone / sensitive vicinity');
  }

  // Community support weight
  if (supportCount >= 20) {
    score += 25;
    factors.push(`High community resonance (${supportCount}+ citizens impacted)`);
  } else if (supportCount >= 10) {
    score += 15;
    factors.push(`Significant community concern (${supportCount} citizens supporting)`);
  } else if (supportCount >= 5) {
    score += 10;
    factors.push(`Multiple citizens supporting (${supportCount})`);
  }

  // Aging issue without resolution
  if (hoursSinceReported > 96) {
    score += 15;
    factors.push(`Complaint aging without progress (${Math.round(hoursSinceReported / 24)} days active)`);
  }

  // Derive recommendation
  let recommendedPriority = 'LOW';
  if (score >= 70) {
    recommendedPriority = 'CRITICAL';
  } else if (score >= 50) {
    recommendedPriority = 'HIGH';
  } else if (score >= 30) {
    recommendedPriority = 'MEDIUM';
  } else {
    recommendedPriority = 'LOW';
  }

  return {
    recommendedPriority,
    score: Math.min(100, Math.max(0, score)),
    factors,
    disclaimer: 'Advisory recommendation generated by CodeCivic rules engine. Official priority is finalized by municipal authorities.',
  };
}

module.exports = {
  recommendPriority,
};
